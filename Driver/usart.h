/* ================================= 头文件保护宏 ================================= */
#ifndef __USART_H
#define __USART_H

/* ================================= 依赖头文件包含区 ================================= */
#include "gd32f4xx.h"

/* ================================= 导出宏定义区 ================================= */
/* ----------------------------------------------------------------------------
 * USART0 引脚：PA9(TX 发送) / PA10(RX 接收)，复用 AF7
 *   板载的 CH340C 串口芯片在 PCB 上就接到了这两个脚，所以插板子 USB 口即可通信。
 * ----------------------------------------------------------------------------
 */
#define USART1_GPIO_PORT        GPIOA        /* 端口 A */
#define USART1_GPIO_CLK         RCU_GPIOA    /* GPIOA 的时钟 */
#define USART1_TX_PIN           GPIO_PIN_9   /* 发送脚 PA9 */
#define USART1_RX_PIN           GPIO_PIN_10  /* 接收脚 PA10 */
#define USART1_GPIO_AF          GPIO_AF_7    /* 复用 AF7 = USART0 */

/* ----------------------------------------------------------------------------
 * USART0 外设、时钟与中断号（注意：这里全部指向 USART0，而不是 USART1）
 * ----------------------------------------------------------------------------
 */
#define USART1_PERIPH           USART0        /* 用的外设是 USART0 */
#define USART1_CLK              RCU_USART0    /* USART0 的时钟 */
#define USART1_IRQ              USART0_IRQn   /* USART0 的中断号 */

/* 接收缓冲区大小（角度指令最多 "180" 三个字符，8 个字节留足余量） */
#define USART1_RX_BUF_SIZE      8U

/* ================================= 导出类型定义区 ================================= */

/* ================================= 导出常量定义区 ================================= */

/* ================================= 导出全局变量声明区 ================================= */

/* ================================= 导出函数声明区 ================================= */
/* 初始化 USART0（8N1，115200 等波特率，中断接收），开机调一次 */
void usart1_init(uint32_t baud);

/* 发送单个字节 / 字符串（用于给电脑回显信息） */
void usart1_send_char(uint8_t ch);
void usart1_send_string(const char *str);

/* 轮询获取一行指令（以 \r 或 \n 结尾），返回 1 表示有数据，0 表示无 */
uint8_t usart1_get_line(char *buf, uint8_t maxlen);

/* 接收中断处理，供 gd32f4xx_it.c 中的 USART0_IRQHandler 调用 */
void usart1_irq_handler(void);

#endif /* __USART_H */

