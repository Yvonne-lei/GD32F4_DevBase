/* ================================= 头文件保护宏 ================================= */
/* 防止同一个头文件被重复包含，标准写法，不用改 */
#ifndef __SERVO_H
#define __SERVO_H

/* ================================= 依赖头文件包含区 ================================= */
#include "gd32f4xx.h"   /* 芯片厂商的库，里面有 GPIOB、TIMER1 等所有定义 */

/* ================================= 导出宏定义区 ================================= */
/* ----------------------------------------------------------------------------
 * 舵机 PWM 输出引脚：PB10
 *   为什么是 PB10？因为板子把舵机信号脚接在了 PB10 上（看原理图）。
 *   PB10 的"复用功能1（AF1）"正好是 TIMER1 的通道2，所以用 AF1。
 * ----------------------------------------------------------------------------
 */
#define SERVO_GPIO_PORT         GPIOB        /* 端口 B */
#define SERVO_GPIO_PIN          GPIO_PIN_10  /* 第 10 号引脚 = PB10 */
#define SERVO_GPIO_CLK          RCU_GPIOB    /* GPIOB 的时钟（用前要开） */
#define SERVO_GPIO_AF           GPIO_AF_1    /* 复用功能编号 AF1 = TIMER1 */

/* ----------------------------------------------------------------------------
 * 舵机使用的定时器：TIMER1（挂在 APB1 总线上，定时器时钟 84MHz）
 *   通道选择 TIMER_CH_2（GD32 的通道从 0 开始编号：CH0/CH1/CH2/CH3）
 *   注意：GD32 的"CH2"对应 STM32 里的"CH3"，别和 STM32 的命名搞混。
 * ----------------------------------------------------------------------------
 */
#define SERVO_TIMER             TIMER1        /* 用定时器 1 */
#define SERVO_TIMER_CLK         RCU_TIMER1    /* TIMER1 的时钟（用前要开） */
#define SERVO_TIMER_CH          TIMER_CH_2    /* 用通道 2（对应 PB10） */

/* 角度范围（0 ~ 180°），超出会被 servo_set_angle 自动钳到 180 */
#define SERVO_ANGLE_MIN         0U
#define SERVO_ANGLE_MAX         180U

/* ================================= 导出类型定义区 ================================= */

/* ================================= 导出常量定义区 ================================= */

/* ================================= 导出全局变量声明区 ================================= */

/* ================================= 导出函数声明区 ================================= */
/* 初始化舵机 PWM（50Hz，上电默认转到 90° 居中）。
 * 程序启动时在 main() 里调用一次即可。 */
void servo_init(void);

/* 设置舵机角度（0 ~ 180），自动钳位到有效范围。
 * 串口收到数字后，最终就是调这个函数让舵机转。 */
void servo_set_angle(uint32_t angle);

#endif /* __SERVO_H */

